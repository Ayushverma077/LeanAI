/// Roles involved in a guided agent workflow (Instructions §9.2, FR-29).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AgentRole {
    Orchestrator,
    Planner,
    ContextBuilder,
    Analyst,
    Coder,
    Validator,
    Tester,
    Reviewer,
}

/// Permitted tool capabilities (Instructions §9.2, ADR 0010).
/// Consequential capabilities (WriteFile, RunCommand, WebAccess) require scoped approval.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ToolCapability {
    ReadFile,
    ListDirectory,
    InspectContextIndex,
    ProposePatch,
    RunAllowlistedCommand,
    WriteFile,
    WebAccess,
}

/// Hard resource ceilings for a task run (FR-26, 8.1).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TaskBudget {
    pub max_tokens: u64,
    pub max_cost_usd: f64,
    pub max_iterations: u32,
    pub timeout_ms: u64,
}

impl Default for TaskBudget {
    fn default() -> Self {
        Self {
            max_tokens: 128_000,
            max_cost_usd: 1.50,
            max_iterations: 10,
            timeout_ms: 120_000,
        }
    }
}

